// 清干净：类型认不出的栏目等于没配（直接丢）；星期认不出当"日子自定"，排产时自己挑
function normalizeColumns(raw) {
  const out = [];
  (Array.isArray(raw) ? raw : []).forEach(function (c, i) {
    if (!c || typeof c !== 'object') return;
    const t = typeOf(c.type);
    if (!t) return;
    const day = Number(c.day);
    out.push({
      id: String(c.id || ('c' + (i + 1))).slice(0, 24),
      name: String(c.name || '').trim().slice(0, 20) || t.name,
      day: (day >= 1 && day <= 7) ? day : 0,
      type: t.key,
      note: String(c.note || '').trim().slice(0, 60),
    });
  });
  return out;
}
// 栏目表的问题（只提示、不拦人）：同一天两个栏目会撞车；栏目那一类缺料这周就排不出它
function columnsProblems(cols, materials) {
  const list = Array.isArray(cols) ? cols : [];
  const problems = [];
  const byDay = {};
  list.forEach(function (c) {
    if (!c || !c.day) return;
    if (byDay[c.day]) problems.push('「' + byDay[c.day] + '」和「' + c.name + '」都排在' + columnDayName(c.day) + '——同一天两个栏目会撞车，改一个的日子');
    else byDay[c.day] = c.name;
  });
  if (list.length > 7) problems.push('一周只有 7 天，栏目却有 ' + list.length + ' 个——排不下，先合并或删掉几个');
  if (materials) {
    list.forEach(function (c) {
      const chk = checkType(c.type, materials);
      if (!chk.ok) problems.push('栏目「' + c.name + '」是做' + _typeName(c.type) + '的，但' + chk.needText + '——补齐才会排进这一栏');
    });
  }
  return problems;
}
