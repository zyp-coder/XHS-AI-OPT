// 权重 → 篇数（最大余数法：先按比例取整，余下的篇数给小数部分最大的那几个）
function allocate(mix, total) {
  const rows = (mix || []).filter(r => Number(r.share) > 0);
  const n = Math.max(1, Math.min(60, parseInt(total, 10) || 12));
  const sum = rows.reduce((a, r) => a + Number(r.share), 0);
  if (!rows.length || sum <= 0) return [];
  const out = rows.map(function (r) {
    const exact = Number(r.share) / sum * n;
    const base = Math.floor(exact);
    return { row: r, base: base, frac: exact - base };
  });
  let left = n - out.reduce((a, o) => a + o.base, 0);
  out.slice().sort(function (a, b) { return (b.frac - a.frac) || (b.row.share - a.row.share); })
    .forEach(function (o) { if (left > 0) { o.base += 1; left -= 1; } });
  return out.filter(o => o.base > 0).map(function (o) {
    return { type: o.row.type, goal: o.row.goal, ex: o.row.ex, count: o.base, share: Math.round(o.row.share / sum * 100) };
  });
}

