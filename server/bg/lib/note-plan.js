// 形态词汇表（needsForm / formBan 只用这两个词，够用就好）：list＝分点/编号/一条条列；oneLine＝一句一段
const FORM_NAMES = { list: '分点 / 编号', oneLine: '一句一段' };
function _forms(v) { return (Array.isArray(v) ? v : []).filter(k => FORM_NAMES[k]); }

// 这一篇的类型块（喂成稿 / 改稿 / 挑稿提示词）。四十五改起它是"这篇怎么讲"的**唯一**主约束（调子已退市）：
//   这条线 / 这种写法的节拍（顺序）＋ 形态 ＋ 要写出来的东西 ＋ 戒条 ＋ 类样本 ＋ 📐 篇幅配比 ＋ 🖋 字数。
//   形态仍归类型（四十改 A 立的口径）：要不要分点 / 编号 / 一条条列、按什么顺序走，全看这一块；
//   原「调子 × 类型打架」那套 B 兜底（formClashOf）已随调子删除——现在没有第二方来挡形态。
//   两类戒条的分界照旧（别混）：**形态类**（这条线要求 / 禁止分点、一句一段）跟着节拍走；
//   **内容·态度类**（不许编年代人名、不许催促推销、不许两头讨好、不许煽情、不许拿没根的数据）＝无条件守住。
// kindKey 有值时，写法自带的 beats/must/taboo/samples/shape/words 盖过所属线的（写法比线细）。
// opts（都可省）：custom＝账号在任务配置改出来的那份默认（config.noteStyle，读 lines / kinds）；
//   words＝这一篇的字数档 key；talk＝这一篇的 🎚 卖货话术比例 key；talkWins＝④ 本篇临时拨过话术（拨过就本篇说了算）。
function describeTypeScript(typeKey, kindKey, opts) {
  const t = typeOf(typeKey);
  if (!t) return '';
  const o = opts || {};
  const k = kindOf(kindKey);
  const kk = (k && k.type === t.key) ? k : null;
  const pickKey = kk ? kk.key : '';
  const beats = ((kk && kk.beats && kk.beats.length) ? kk.beats : (t.beats || []));
  const must = (kk && kk.must) || t.must || '';
  const taboo = (kk && kk.taboo) || t.taboo || '';
  const sm = (kk && kk.samples) || t.samples || {};
  const head = '★ 这一篇是「' + t.name + (kk ? ' · ' + kk.name : '') + '」——' + (kk ? kk.form : t.what);
  if (!beats.length) return head;
  const lines = [head];
  lines.push('· 第一优先级：正文**怎么讲**按这一类（这种写法）的节拍与形态来——与通用写法（钩子→共情→干货→软广→CTA 那类模板）冲突时，以这一块为准。');
  const need = _forms((kk && kk.needsForm) || t.needsForm);
  const ban = _forms((kk && kk.formBan) || t.formBan);
  if (need.length) lines.push('· 形态：这一类**要' + need.map(f => FORM_NAMES[f]).join('、') + '**（这就是它的魂，别压成一段流水）');
  if (ban.length) lines.push('· 形态：这一类**不许' + ban.map(f => FORM_NAMES[f]).join('、') + '**——用叙事或情绪一路讲下来');
  lines.push('· 这一类必须走过的节拍（顺序别颠倒）：');
  beats.forEach((b, i) => lines.push('  ' + (i + 1) + '. ' + b));
  if (must) lines.push('· 这一类要写出来的东西（写不到位＝这一类白写）：' + must);
  if (taboo) lines.push('· 这一类的戒条（违反＝写错了这一类）：' + taboo);
  const own = shapeOwn(t.key, pickKey, o.custom);
  const talk = o.talk ? ((typeof o.talk === 'object') ? o.talk : sellTalkOf(o.talk)) : null;
  const talkWins = !!(o.talkWins);
  const sh = shapeOf(t.key, pickKey, o.custom, talk, { talkWins: talkWins });
  const w = wordsOf(o.words) || wordsOf(wordsBaseOf(t.key, pickKey, o.custom)) || wordsOf(WORDS_DEFAULT);
  if (sh && w) {
    const seg = (pct) => Math.round(w.mid * pct / 100 / 10) * 10;
    lines.push('· 篇幅配比（按整篇正文字数算）：铺垫 ≈ ' + sh.build + '%（约 ' + seg(sh.build) + ' 字）／ 广告 ≈ ' + sh.sell + '%' + (sh.sell > 0 ? '（约 ' + seg(sh.sell) + ' 字）' : '（不出现）') + '——' + shapeTail(sh.sell));
    if (talk) {
      if (own && talkWins) {
        lines.push('· 本篇产品篇幅已按「' + talk.name + '」临时拨到 ' + sh.sell + '%' + (own.sell !== sh.sell ? '（这条线账号默认单独定过 ' + own.sell + '%）' : '') + '：节拍照走，篇幅按这个数分配。');
      } else if (own) {
        lines.push('· 本条线的产品篇幅在账号默认里单独定过：广告 ≈ ' + sh.sell + '%。');
      } else if (sh.sell === 0) {
        lines.push('· 本条已按「' + talk.name + '」设为不出现产品：节拍里涉及产品的动作（出现 / 带出 / 轻点）一律跳过，产品名字不许进正文。');
      } else {
        lines.push('· 本条产品篇幅按「' + talk.name + '」走（约占正文 ' + sh.sell + '%）。');
      }
    }
  }
  if (w) lines.push('· 字数：这篇写 ' + w.range + '（' + w.name + '档；平台规则若另有总长要求，以平台为准）');
  const op = Array.isArray(sm.openers) ? sm.openers : [];
  const ti = Array.isArray(sm.titles) ? sm.titles : [];
  if (op.length || ti.length) {
    lines.push('★ 类样本（照这个味道写，别照抄字句）：' +
      (op.length ? '开篇像这样——「' + op.join('」「') + '」' : '') +
      (ti.length ? (op.length ? '；' : '') + '标题像这样——「' + ti.join('」「') + '」' : ''));
  }
  return lines.join('\n');
}

