    return '· ' + (c.day ? columnDayName(c.day) : '（日子自定）') + '｜' + _typeName(c.type) + '｜栏目名「' + c.name + '」'
      + (short ? '（⚠ 这一类现在缺料，这次先排不了，别硬排）' : '');
