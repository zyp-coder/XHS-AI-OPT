// 两段配比＝铺垫 / 广告 各占正文百分之几（展开段退市，出厂三段数据折进来兼容，见 normShape）；
//   厂里给每条线一份（TYPES[].shape），「发笔记 → 任务配置 → 内容基调」那些基调卡上拖过条的那条线／那种写法存成账号默认
