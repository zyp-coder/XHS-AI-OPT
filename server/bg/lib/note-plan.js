// 一周的固定位（UI 与提示词共用）：周一 栏目A（热点）· 周四 栏目B（知识·干货）
function describeWeek(cols) {
  const list = (Array.isArray(cols) ? cols : []).slice().sort(function (a, b) { return (a.day || 9) - (b.day || 9); });
  if (!list.length) return '';
  return list.map(c => (c.day ? columnDayName(c.day) : '日子自定') + ' ' + c.name + '（' + _typeName(c.type) + '）').join(' · ');
}
// 每个栏目每周一篇：类型由栏目定死。AI 排漏了就地补上——先找"同类型且没认领"的那篇，
//   没有就把还没认领的一篇改成栏目这一类的（标题/凭据留着，别凭空造一篇没凭据的）。
function applyColumns(items, cols) {
  const list = (Array.isArray(items) ? items : []).map(function (x) {
    const it = Object.assign({}, x);
    const t = typeOf(it.type);
    if (t) it.type = t.key;   // 老排产表里存的旧键（八类那批）先翻成新键，栏目才认得出它
    return it;
  });
  (Array.isArray(cols) ? cols : []).forEach(function (c) {
    let pick = list.filter(x => !x.col && x.type === c.type)[0] || list.filter(x => !x.col)[0];
    if (!pick) return;
    pick.col = c.name; pick.day = c.day; pick.colId = c.id;
    if (pick.type !== c.type) { pick.type = c.type; pick.kind = ''; }
  });
  const withCol = list.filter(x => x.col).sort(function (a, b) { return (a.day || 9) - (b.day || 9); });
  return withCol.concat(list.filter(x => !x.col)).map(function (x, i) { return Object.assign({}, x, { no: i + 1 }); });
}

