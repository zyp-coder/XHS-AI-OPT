def apply(path, pairs, forbidden):
    with io.open(path, 'r', encoding='utf-8', newline='') as f:
        txt = f.read()
    orig = txt
    for old, new, cnt in pairs:
        got = txt.count(old)
        if got != cnt:
            raise SystemExit('!! %s: 命中 %d 次（应为 %d）\n   %s' % (path, got, cnt, old[:80]))
        txt = txt.replace(old, new)
    for bad in forbidden:
        if bad in txt:
            raise SystemExit('!! %s: 改完仍残留「%s」\n%s' % (path, bad,
                             '\n'.join('  L%d: %s' % (i + 1, ln.strip()[:110])
                                       for i, ln in enumerate(txt.split('\n')) if bad in ln)))
    if txt == orig:
        raise SystemExit('!! %s: 没有任何改动' % path)
    if DRY:
        print('--dry %s: %d 处' % (path, len(pairs)))
        return
    bak = path + '.pre63.bak'
    shutil.copyfile(path, bak)
    tmp = path + '.tmp63'
    with io.open(tmp, 'w', encoding='utf-8', newline='') as f:
        f.write(txt)
    shutil.move(tmp, path)
    print('ok %s: %d 处（备份 %s）' % (path, len(pairs), bak))


