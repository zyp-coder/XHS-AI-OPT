LINE_DELTA = {
    '资料/功能与界面总表.md': 2,
    '资料/视频/AI雕兄口播稿/口播稿-发笔记.md': -1,
    '资料/视频/AI雕兄口播稿/口播稿-发视频.md': -1,
}


def main():
    total_done = 0
    for rel, edits in EDITS.items():
        src = ROOT / rel
        raw = src.read_bytes().decode('utf-8')
        before_lines = raw.count('\n')
        new_raw = raw
        done = []
        for old, new, want in edits:
            c_old = new_raw.count(old)
            if c_old == 0:
                continue                      # 重复跑：这条已换过（针找不到＝已换过）
            assert c_old == want, f'[{rel}] 期望 {want} 处，实际 {c_old} 处：{old[:36]}…'
            new_raw = new_raw.replace(old, new)
            done.append(old[:26])

        if done:
            delta = new_raw.count('\n') - before_lines
            assert delta == LINE_DELTA.get(rel, 0), f'[{rel}] 行数变了 {delta}（期望 {LINE_DELTA.get(rel, 0)}）'

        left = [p for p in FORBID.get(rel, []) if p in new_raw]
        if left:
            raise SystemExit(f'[{rel}] ✗ 旧说法残留：{left}')
        miss = [p for p in REQUIRE.get(rel, []) if p not in new_raw]
        if miss:
            raise SystemExit(f'[{rel}] ✗ 新说法没写上：{miss}')

        if done:
            src.write_bytes(new_raw.encode('utf-8'))
            total_done += len(done)
            print(f'✓ {rel}：改 {len(done)} 处')
            for d in done:
                print('   ·', d + '…')
        else:
            print(f'· {rel}：无需改动')

    print(f'\n{"✓ 本轮共 " + str(total_done) + " 处" if total_done else "· 全部已是最新"}')


if __name__ == '__main__':
    main()
