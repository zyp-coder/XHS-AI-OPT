raw = KB.read_bytes().decode('utf-8')
assert '\n' not in raw.replace('\r\n', ''), '不是纯 CRLF，停'
text = raw.replace('\r\n', '\n')
eol = '\r\n' if '\r\n' in raw else '\n'

miss = []
for needle, new, expect in REPL:
    got = text.count(needle)
    if got != expect:
        miss.append((got, expect, needle[:56]))
if miss:
    for got, expect, n in miss:
        print('  ✗ 命中 %d 处（期望 %d）：%s' % (got, expect, n))
    sys.exit('── 有断言不过，整份不落盘 ──')

out = text
for needle, new, _ in REPL:
    out = out.replace(needle, new)

bak = REPO / 'tmp' / 'backup' / ('知识库_pre-drain2long_%s.json' % __import__('time').strftime('%Y%m%d-%H%M'))
bak.parent.mkdir(parents=True, exist_ok=True)
shutil.copy2(KB, bak)

tmp = KB.with_name(KB.name + '.kbtmp')
tmp.write_bytes(out.replace('\n', eol).encode('utf-8'))
os.replace(tmp, KB)

import json
before = json.loads(raw)
after = json.loads(KB.read_bytes().decode('utf-8'))
assert len(before) == len(after) == 70, '条目数变了'
assert [e['id'] for e in before] == [e['id'] for e in after], 'id 顺序变了'
new_raw = KB.read_bytes().decode('utf-8')
assert '\n' not in new_raw.replace('\r\n', ''), '落盘不是纯 CRLF'
