def rewrite(text, pairs, where):
    for old, new, n in pairs:
        c = text.count(old)
        assert c == n, f'{where}: 期望 {n} 处 {old!r}，实际 {c} 处'
        text = text.replace(old, new)
    return text


def main():
    src = zipfile.ZipFile(OLD)
    from_repo, rewritten, kept = [], [], 0
    with zipfile.ZipFile(NEW, 'w', zipfile.ZIP_DEFLATED) as out:
        for item in src.infolist():
            name = item.filename
            if item.is_dir():
                out.writestr(item, b'')
                continue
            if name in REPO_MAP:
                data = (ROOT / REPO_MAP[name]).read_bytes()
                from_repo.append(name)
            elif name in REPL:
                raw = src.read(name)
                text = raw.decode('utf-8')
                eol = '\r\n' if '\r\n' in text else '\n'
                text = text.replace('\r\n', '\n')
                text = rewrite(text, REPL[name], name)
                data = text.replace('\n', eol).encode('utf-8')
                rewritten.append(name)
            else:
                data = src.read(name)
                kept += 1
            out.writestr(item, data)
    print('新包:', NEW.name)
    print('  用仓库当前版本替换:', len(from_repo))
    for n in from_repo:
        print('    •', n)
    print('  就地改写:', len(rewritten))
    for n in rewritten:
        print('    •', n)
    print('  原样保留:', kept)


main()
