def rewrite(text, pairs, where):
    for old, new, n in pairs:
        c = text.count(old)
        assert c == n, f'{where}: 期望 {n} 处 {old!r}，实际 {c} 处'
        text = text.replace(old, new)
    return text


def render_self_pdf(html_bytes):
    """包内「置顶自评素材库.pdf」按包内（已改好的）HTML 现渲一份。

    旧 PDF 是 2026-09 的成品（Skia/PDF · Letter 单页），脚本一直原样照抄，里面的旧词
    （如「评论区养号」）改不到——每出一版就从 HTML 重渲，PDF 才能跟着 HTML 走。
    """
    import tempfile
    from playwright.sync_api import sync_playwright
    with tempfile.TemporaryDirectory() as td:
        hp = pathlib.Path(td) / 'selfComment.html'
        pp = pathlib.Path(td) / 'selfComment.pdf'
        hp.write_bytes(html_bytes)
        with sync_playwright() as p:
            b = p.chromium.launch()
            pg = b.new_page(viewport={'width': 900, 'height': 1200})
            pg.goto(hp.as_uri(), wait_until='load')
            pg.wait_for_timeout(400)
            pg.pdf(path=str(pp), format='Letter', print_background=True,
                   margin={'top': '8mm', 'bottom': '8mm', 'left': '5mm', 'right': '5mm'})
            b.close()
        return pp.read_bytes()


def main(out=None):
    new = pathlib.Path(out) if out else ROOT / '资料' / ('素材资料-知识包_' + datetime.datetime.now().strftime('%Y%m%d-%H%M') + '.zip')
    src = zipfile.ZipFile(OLD)
    from_repo, rewritten, kept = [], [], 0
    items = []
    for item in src.infolist():
        name = item.filename
        if item.is_dir():
            items.append((item, b''))
            continue
        if name in REPO_MAP:
            data = (ROOT / REPO_MAP[name]).read_bytes()
            from_repo.append(name)
        elif name.endswith(('笔记内容.md', '话术脚本.md')) or name in NOTE_JS:
            data = rewrite_note(name, src.read(name))
            rewritten.append(name)
        elif name in REPL:
            raw = src.read(name)
            text = raw.decode('utf-8')
            eol = '\r\n' if '\r\n' in text else '\n'
            text = text.replace('\r\n', '\n')
            text = rewrite(text, REPL[name], name)
            data = text.replace('\n', eol).encode('utf-8')
            rewritten.append(name)
        else:
            data = src.read(name)
            kept += 1
        if name.endswith(('.md', '.js', '.json', '.html')) and name not in RESIDUE_ALLOW and name not in RESIDUE_REPO_SKIP:
            try:
                text = data.decode('utf-8')
            except UnicodeDecodeError:
                text = ''
            for pat in RESIDUE_FORBID:
                m = pat.search(text)
                assert not m, f'{name}: 还残留找入口类指令 {m.group(0)!r}（该改的没改到，或该进 RESIDUE_ALLOW）'
        items.append((item, data))
    html_data = next((d for it, d in items if it.filename == '置顶自评素材库.html'), None)
    if html_data:
        pdf_bytes = render_self_pdf(html_data)
        items = [(it, pdf_bytes if it.filename == '置顶自评素材库.pdf' else d) for it, d in items]
        print('  置顶自评素材库.pdf 现渲:', len(pdf_bytes) // 1024, 'KB')
    with zipfile.ZipFile(new, 'w', zipfile.ZIP_DEFLATED) as out:
        for item, data in items:
            out.writestr(item, data)
    print('新包:', new.name)
    print('  用仓库当前版本替换:', len(from_repo))
    for n in from_repo:
        print('    •', n)
    print('  就地改写:', len(rewritten))
    for n in rewritten:
        print('    •', n)
    print('  原样保留:', kept)


if __name__ == '__main__':
    main()
