# -*- coding: utf-8 -*-
"""一次性：调子补「魂」（篇幅配比 + 戒条 + 🖋 字数档），卖货话术比例接管产品段（2026-09-28 三十七改）的资料侧同步 —— 知识库 JSON。

口径（真源 `extension/lib/note-plan.js` 的 STYLE_ROUTES.shape / taboo / words、WORDS、SELL_TALK.pct、shapeOf()，
给人看的那份是 资料/功能与界面总表.md 顶部两行与 资料/推广物料/使用说明.md 三十七改）：
八条路线除叙事骨架外，各带 **篇幅配比**（铺垫 / 展开 / 产品三块百分比，凑 100%）＋ **戒条**（这条调子绝不许出现什么）
＋ **推荐字数档**（短 300-500 / 中 500-800 / 长 800-1500 字）；
**🎚 卖货话术比例直接接管配比里的产品段**（0 / 10 / 25 / 50），剩下按「铺垫 : 展开」归一；
字数默认跟路线建议的，发笔记 ④ 可就地改这一篇的；配比进成稿提示词是第一优先级。

改这 3 处（客户照着点会点错、或这轮之后会答错的地方）：
  drain028 发笔记向导：④ 那段补「篇幅配比 / 戒条 / 字数」
  nav002   ⑧ 规划那节点：账号默认调子补「配比与戒条」
  nav005   发笔记 4 页 ① 写一篇：④ 补字数档与配比口径

格式安全：这个文件是「2 空格缩进 + 行尾 `, `（逗号带一个空格）」的序列化风格、LF 换行，
直接 json.dump 会整篇重排。脚本先把原文反序列化再按同一风格重建，要求与原文逐字节一致
（不一致就报错退出、不写盘），每条替换都断言「恰好命中 1 处」。
"""
import io
import json
import sys
from pathlib import Path

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')

ROOT = Path(__file__).resolve().parents[2]
KB = ROOT / '资料' / '小红书AI引流工具知识库.json'

# 终检：新写的字不许带这些（对外合规底线 + 这轮之前的旧口径）
FORBID = [
    '防封', '反爬', '养号', '规避',
    '副调子', '全篇以卖点', '只是换个开头',
]


def dump(data):
    return json.dumps(data, indent=2, ensure_ascii=False).replace(',\n', ', \n')


def sub(node, key, old, new):
    text = node[key]
    n = text.count(old)
    assert n == 1, f"{node.get('id')}.{key}: 期望命中 1 处，实际 {n} 处 —— {old[:40]}"
    node[key] = text.replace(old, new)


def main():
    raw = KB.read_bytes().decode('utf-8')
    eol = '\r\n' if '\r\n' in raw else '\n'
    data = json.loads(raw)
    assert dump(data) == raw.replace('\r\n', '\n'), '序列化风格复刻失败：重建后与原文不一致，先对齐格式再改内容'

    by_id = {e['id']: e for e in data}
    for i in ('drain028', 'nav002', 'nav005'):
        assert i in by_id, f'缺条目 {i}'

    # ── drain028 · 发笔记向导 ────────────────────────────────────────
    sub(by_id['drain028'], 'content',
        '④叙事风格：定这条按什么调子讲（默认沿用「诊断&配置 → ⑧ 规划」定好的账号调子，八条路线可就地换这一条）＋这篇卖多少（卖货话术比例四档：不提产品 / 轻带一句 / 自然安利 / 主打推荐，改了只影响这一条，不动账号默认）；⑤写成稿：',
        '④叙事风格：定这条按什么调子讲、卖多少、写多长——默认沿用「诊断&配置 → ⑧ 规划」定好的账号调子（八条路线可就地换这一条；'
        '每条调子都带「篇幅配比」：铺垫 / 展开 / 产品三块各占多少——文艺慢调就是前面一大段铺垫、产品只在收尾出现一次，'
        '以及一条「戒条」＝这条调子绝不许出现什么，都在卡上直接摆出来）；卖货话术比例四档（不提产品 / 轻带一句 / 自然安利 / 主打推荐），'
        '它直接决定产品那段占多少；字数三档（短 300-500 / 中 500-800 / 长 800-1500 字，默认跟这条调子建议的）。'
        '改了这一条的都只影响这一条，不动账号默认；⑤写成稿：')

    # ── nav002 · ⑧ 规划节点 ────────────────────────────────────────
    sub(by_id['nav002'], 'content',
        '顶上先定 🎨 调子（账号默认——笔记按它怎么写、卖货话术占多少，发笔记默认沿用它、单篇可就地换）',
        '顶上先定 🎨 调子（账号默认——笔记按它怎么写、卖多少、写多长；每条约带「篇幅配比」（铺垫 / 展开 / 产品各占多少）与一条「戒条」，'
        '卡上直接摆出来，发笔记默认沿用它、单篇可就地换）')

    # ── nav005 · 发笔记 4 页 ① 写一篇 ───────────────────────────────
    sub(by_id['nav005'], 'content',
        '④ 叙事风格＝这条按什么调子讲、卖多少——默认沿用「诊断&配置 → ⑧ 规划」定好的账号调子与卖货话术比例，八条路线可就地换这一条的、卖货话术比例四档（不提产品 / 轻带一句 / 自然安利 / 主打推荐）也能改（只动这一条，不动账号默认）。',
        '④ 叙事风格＝这条按什么调子讲、卖多少、写多长——默认沿用「诊断&配置 → ⑧ 规划」定好的账号调子与卖货话术比例；'
        '八条路线可就地换这一条的、卖货话术比例四档（不提产品 / 轻带一句 / 自然安利 / 主打推荐）与字数三档（短 300-500 / 中 500-800 / 长 800-1500 字）也能改（只动这一条，不动账号默认）。'
        '这一页还会摆出该调子的「篇幅配比」——铺垫 / 展开 / 产品各占多少、约多少字，以及一条「戒条」；配比进成稿提示词是第一优先级，'
        '所以「文艺慢调」写出来是前面一大段铺垫、产品只在收尾出现一次。')

    out = dump(data)
    for bad in FORBID:
        assert bad not in out, f'终检失败：不该再出现「{bad}」'
    assert '"id": "drain028"' in out

    KB.write_bytes((out.replace('\n', eol) if eol == '\r\n' else out).encode('utf-8'))
    print('已写盘：', KB)
    for i in ('drain028', 'nav002', 'nav005'):
        e = by_id[i]
        print(' ', i, '|', e['title'])
        for frag in ('篇幅配比', '戒条', '字数'):
            assert frag in e['content'], f'{i} 少了「{frag}」'
        print('      篇幅配比 / 戒条 / 字数 均已在正文里')


if __name__ == '__main__':
    main()
