def run():
    bad = 0
    for rel, cfg in RULES.items():
        path = os.path.join(ROOT, rel)
        want_crlf = dict(cfg)['crlf']
        raw = io.open(path, encoding='utf-8').read()
        s = raw.replace('\r\n', '\n')
        for find, repl, expect in dict(cfg)['rules']:
            cnt = s.count(find)
            if cnt != expect:
                print('MISS[%d/%d] %s :: %s' % (cnt, expect, rel, find[:46]))
                bad += 1
                continue
            s = s.replace(find, repl)
        out = s.replace('\n', '\r\n') if want_crlf else s
        if out != raw:
            io.open(path, 'w', encoding='utf-8', newline='').write(out)
            print('written:', rel)
    if bad:
        print('未落盘规则数 =', bad)
        sys.exit(1)
    print('ALL OK')


if __name__ == '__main__':
    run()
