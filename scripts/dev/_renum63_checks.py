def merged():
    out = {}
    for src in (PLAN, PLAN_B, PLAN_C):
        for name, pairs in src.items():
            out.setdefault(name, []).extend(pairs)
    return out


def main():
    dry = '--dry' in sys.argv
    total = 0
    for name, pairs in merged().items():
        path = DEV / name
        text = path.read_text(encoding='utf-8')
        for old, new, want in pairs:
            got = text.count(old)
            if got != want:
                raise SystemExit('%s: 这条命中 %d 次（要 %d 次）：%s' % (name, got, want, old[:60]))
            text = text.replace(old, new)
            total += 1
        for bad in FORBIDDEN.get(name, []):
            if bad in text:
                raise SystemExit('%s: 还有旧口径「%s」没改干净' % (name, bad))
        if dry:
            print('dry %s: %d 条' % (name, len(pairs)), flush=True)
            continue
        bak = path.with_suffix(path.suffix + '.pre63.bak')
        if not bak.exists():
            shutil.copyfile(path, bak)
        tmp = path.with_suffix(path.suffix + '.tmp63')
        tmp.write_text(text, encoding='utf-8', newline='\n')
        shutil.move(str(tmp), str(path))
        print('ok %s: %d 条（备份 %s）' % (name, len(pairs), bak.relative_to(ROOT)), flush=True)
    print('共 %d 条%s' % (total, '（没落盘）' if dry else ''), flush=True)


main()
