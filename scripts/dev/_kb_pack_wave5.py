def main():
    raw = io.open(PATH, encoding='utf-8', newline='').read()
    eol = '\r\n' if '\r\n' in raw else '\n'          # 这文件是 CRLF 落盘，切行与写回都得照它来
    lines = raw.split(eol)

    # 断言：这一版还没打过补丁（重复跑会因下面任一断言失败而拒绝）
    assert '跟着 6 页走' not in raw and '六页配置' not in raw.replace('6 页配置', ''), '已经打过补丁'
    # 单行替换不改变行数，必须先跑：BLOCKS 会把段落行数改掉，之后原始行号就不成立了
    for no, (must, new) in sorted(LINES.items(), reverse=True):
        assert must in lines[no - 1], '第 %d 行没命中 %s（现在是：%s）' % (no, must, lines[no - 1][:60])
        lines[no - 1] = new

    for a, b, new in sorted(BLOCKS, reverse=True):
        assert lines[a - 1].strip().startswith("'''") or lines[a - 1].lstrip().startswith("'''") or True
        seg = lines[a - 1:b]
        joined = eol.join(seg)
        key = '跟着 9 步走' if a == 606 else '9 步工作流'
        assert key in joined, '第 %d-%d 行段里没找到 %s' % (a, b, key)
        assert seg[-1].rstrip().endswith("''', 1),") or a == 606, repr(seg[-1][-30:])
        lines[a - 1:b] = new

    body = eol.join(lines)
    assert body.count(LOG_NEW.strip('\n')) == 0
    marker = '正式包仍＝ 素材资料-知识包_20260924-2304.zip）。' + eol + '"""' + eol
    assert body.count(marker) == 1, '没找到顶部说明的收尾位置'
    body = body.replace(marker, '正式包仍＝ 素材资料-知识包_20260924-2304.zip）。' + eol
                        + LOG_NEW.replace('\n', eol) + '"""' + eol)

