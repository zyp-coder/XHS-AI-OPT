    assert '⑥ 说话风格' not in body.split('REPL = {')[1], 'REPL 目标文案里还残留「⑥ 说话风格」'
    assert '第⑨步' not in body.split('REPL = {')[1], 'REPL 目标文案里还残留「第⑨步」'
    assert '去出料' not in body.split('REPL = {')[1], 'REPL 目标文案里还残留「去出料」'

    io.open(PATH, 'w', encoding='utf-8', newline='').write(body)
