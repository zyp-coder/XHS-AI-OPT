def main():
    raw_bytes = KB.read_bytes()
    raw = raw_bytes.decode('utf-8')
    eol = '\r\n' if '\r\n' in raw else '\n'
    data = json.loads(raw)
    assert dump(data) == raw.replace('\r\n', '\n'), '序列化风格复刻失败：重建后与原文不一致，先对齐格式再改内容'

    by_id = {e['id']: e for e in data}
    assert 'drain054' in by_id, '缺锚点条目 drain054'
    assert not any(e['id'].startswith('drain05') and e['id'] > 'drain054' for e in data), 'drain055 之后已有条目，先核对编号'

    # 1) 旧口径改口：先在内存里逐处替换，任一处不中即整体放弃
    for id_, old, new in PATCHES:
        e = by_id[id_]
        hay = e['title'] + '\n' + e['content']
        assert hay.count(old) == 1, f'{id_} 命中 {hay.count(old)} 处（应为 1）：{old[:40]}…'
        if old.startswith('新建笔记·'):
            e['title'] = new
        else:
            assert old in e['content'], f'{id_}：这句不在正文里（只出现在标题？）：{old[:40]}…'
            e['content'] = e['content'].replace(old, new, 1)
            assert old not in e['content'], f'{id_} 替换后旧串还在：{old[:40]}…'
    # drain037 tags 补一颗
    t37 = by_id['drain037']['tags']
    if '门面笔记' not in t37:
        t37.append('门面笔记')

    # 2) 追加三条新条目（插在 drain054 后面、drain_arch 前面）
    ts0 = max(e['createdAt'] for e in data) + 1000
    entries = build_entries(ts0)
    for e in entries:
        assert e['id'] not in by_id, f"{e['id']} 已存在，别再插"
    new_text = '\n'.join(e['content'] + e['title'] for e in entries)
    for w in FORBID + NEW_ONLY_FORBID:
        assert w not in new_text, f'新条目里出现禁用词/旧术语：{w}'
    idx = data.index(by_id['drain054'])
    data[idx + 1:idx + 1] = entries

    text = dump(data)
    for w in FORBID:
        assert w not in text, f'整库残留禁用词/旧说法：{w}'
    for rx in FORBID_RE:
        assert not rx.search(text), f'整库命中知识包禁则：{rx.pattern}'
    for w in COUNT_EQ:
        assert text.count(w) == raw.count(w), f'「{w}」出现次数变了（存量 {raw.count(w)} → 现在 {text.count(w)}）'
    assert '四方向一页' not in text, 'drain037 旧标题还在'
    assert '弹层第一行' not in text, 'drain048 的「弹层第一行」还在'
    assert '按四个方向建一篇' not in text, 'nav005 旧句还在'

    out = text.replace('\n', eol).encode('utf-8')
    assert out.count(b'\r\n') == out.count(b'\n'), '换行不纯 CRLF'
    json.loads(out.decode('utf-8'))
    assert len(json.loads(out.decode('utf-8'))) == len(data)

    bak = ROOT / 'tmp' / '门面知识库备份-改前.json'
    bak.parent.mkdir(exist_ok=True)
    bak.write_bytes(raw_bytes)
    tmp = KB.with_suffix('.json.tmp')
    tmp.write_bytes(out)
    os.replace(tmp, KB)
    print(f'OK：知识库补 {len(entries)} 条、改口 {len(PATCHES)} 处（共 {len(data)} 条，全启用 {sum(1 for e in data if e["isActive"])}）')
    print('新增：' + ' / '.join(e['id'] for e in entries))
    print(f'字节：{len(raw_bytes)} → {len(out)}；改前备份＝{bak.relative_to(ROOT)}')


