def main():
    with io.open(PATH, 'r', encoding='utf-8', newline='') as f:
        text = f.read()
    bad = []
    for old, new, expect in EDITS:
        got = text.count(old)
        if got != expect:
            bad.append((old[:60], expect, got))
            continue
        text = text.replace(old, new)
    if bad:
        for b in bad:
            print('MISS 期望 %d 处、实际 %d 处：%s' % (b[1], b[2], b[0]))
        sys.exit(1)
    with io.open(PATH, 'w', encoding='utf-8', newline='') as f:
        f.write(text)
    print('OK：%d 处替换完成' % len(EDITS))


if __name__ == '__main__':
    main()
