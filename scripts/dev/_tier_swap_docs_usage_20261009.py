def apply(text, old, new, tag):
    # new 可能内嵌 old（留档场景），先看 new 在不在，在＝已应用
    if text.count(new) >= 1:
        print(f'{tag}: 已应用，跳过')
        return text, False
    c = text.count(old)
    assert c == 1, f'{tag}: 期望 1 处，实际 {c} 处'
    return text.replace(old, new), True


