    # 新条目文字先过一遍（禁用词 / 旧术语都不许出现在新文字里）
    new_text = '\n'.join(e['content'] + e['title'] + ' '.join(e['tags']) for e in entries)
    for w in FORBID + NEW_ONLY_FORBID:
        assert w not in new_text, f'新条目里出现禁用词/旧术语：{w}'

    # 存量校准：逐处精确命中一次
    for id_, field, old, new in content_fixes():
        e = by_id[id_]
        cur = e[field]
        assert cur.count(old) == 1, f'{id_}.{field} 命中 {cur.count(old)} 次（应为 1）：{old[:40]}…'
        e[field] = cur.replace(old, new, 1)
    for id_, (old_tags, new_tags) in TAGS_FIXES.items():
        e = by_id[id_]
        assert e['tags'] == old_tags, f'{id_}.tags 与预期不符：{e["tags"]}'
        e['tags'] = new_tags

    idx = data.index(by_id['drain047'])
    data[idx + 1:idx + 1] = entries

    text = dump(data)
    for w in FORBID:
        assert w not in text, f'整库残留禁用词/旧说法：{w}'
    for rx in FORBID_RE:
        assert not rx.search(text), f'整库命中知识包禁则：{rx.pattern}'
    for w in COUNT_EQ:
        assert text.count(w) == raw.count(w), f'「{w}」出现次数变了（存量 {raw.count(w)} → 现在 {text.count(w)}）'

    KB.write_bytes(text.replace('\n', eol).encode('utf-8'))
    ids = [e['id'] for e in data]
    print(f'OK：知识库已补 {len(entries)} 条（{ids.index("drain048")} 起，共 {len(data)} 条）')
    print('新增：' + ' / '.join(e['id'] for e in entries))
    print('校准：drain037（标题+内容+tags）/ drain040（内容+tags）/ nav005（内容）')


