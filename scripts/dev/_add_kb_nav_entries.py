def dumps_style(obj, indent=2):
    """按原文件的风格序列化：2 空格缩进 + 每行结尾逗号后带一个空格。"""
    text = json.dumps(obj, ensure_ascii=False, indent=indent)
    return text.replace(',\n', ', \n')


def main():
    raw = KB.read_text(encoding='utf-8')
    data = json.loads(raw)

    rebuilt = '[\n' + ', \n'.join('  ' + dumps_style(e).replace('\n', '\n  ') for e in data) + '\n]'
    if rebuilt != raw:
        raise SystemExit('✗ 风格复刻不一致，未写盘（需要人工核对序列化格式）')
    print('✓ 风格复刻一致（%d 条原样重建）' % len(data))

    ids = {e['id'] for e in data}
    for e in NEW:
        assert e['id'] not in ids, 'id 撞车: ' + e['id']
        for pat in FORBID:
            assert pat not in e['content'] and pat not in e['title'], f"{e['id']} 命中禁用说法: {pat}"

    now = int(time.time() * 1000)
    out = []
    for i, e in enumerate(NEW):
        out.append({
            'category': e['category'],
            'tags': e['tags'],
            'image': None,
            'title': e['title'],
            'content': e['content'],
            'role': '运营顾问',
            'createdAt': now + i,
            'id': e['id'],
            'isActive': True,
        })

    head = raw[:raw.rfind('\n]')]                       # 到最后一个 '  }'
    body = ', \n'.join('  ' + dumps_style(e).replace('\n', '\n  ') for e in out)
    new_raw = head + ', \n' + body + '\n]'
    KB.write_text(new_raw, encoding='utf-8', newline='\n')

    check = json.loads(KB.read_text(encoding='utf-8'))
    assert len(check) == len(data) + len(NEW)
    assert len({e['id'] for e in check}) == len(check)
